CHECKS = [
    {"id": f"{index:03d}", "title": title, "category": category}
    for index, (category, title) in enumerate(
        ((category, title) for category, titles in _SECTIONS for title in titles), 1
    )
]


def checklist_markdown():
    """Return the exact public acceptance requirements, grouped for reading."""
    lines = []
    previous = None
    for check in CHECKS:
        if check["category"] != previous:
            previous = check["category"]
            lines.extend(["", f"### {previous}", ""])
        lines.append(f"- **{check['id']}** {check['title']}")
    return "\n".join(lines).strip()


